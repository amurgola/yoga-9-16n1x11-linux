#!/usr/bin/env python3
"""Reconstruct the CCU 0xa0 register-write payloads {addr, mask, value} from the Windows register
dump: the last write to each register must satisfy (reg_final & mask) == (value & mask). Earlier
writes and the 0xa1-0xa4 PHY-setup messages take the Surface's values unless both of our captures
agree on something else. usage: ccusnoop-reconstruct.py c1.log c2.log surface_ccu_replay.h out.h"""
import re,sys
c1,c2,surf,out=sys.argv[1:5]
def msgs(log):
    O=[]
    for l in open(log,errors='replace'):
        m=re.match(r'mb0 w=(\d+) ft=(\d+) cmd=0x([0-9a-f]+) len=(\d+) st=0x([0-9a-f]+) pl:(.*)',l.strip())
        if m and 1<=int(m[1])<=500:
            ln=int(m[4]); O.append([int(m[2]),int(m[3],16),ln,[int(x,16) for x in m[6].split()][:ln]])
    return O
def dump(log):
    D=[];cur=None
    for l in open(log,errors='replace'):
        l=l.rstrip('\r\n')
        if l.startswith('=== DUMP'): cur={}; D.append(cur); continue
        m=re.match(r'\s+(\w+)\+([0-9a-f]+):\s+(.*)',l)
        if m and cur is not None:
            for i,v in enumerate(m[3].split()): cur[(m[1],int(m[2],16)+4*i)]=int(v,16)
    return [d for d in D if ('omux1',0x100a0) in d and d[('omux1',0x100a0)]][-1]
A,B=msgs(c1),msgs(c2); W=dump(c1)
S=[]
for m in re.finditer(r'\{\s*(\d+),\s*(0x[0-9a-f]+),\s*(\d+),\s*\{([^}]*)\}\s*\}',open(surf).read()):
    S.append([int(m[1]),int(m[2],16),int(m[3]),[int(x,16) for x in re.findall(r'0x[0-9a-f]{2}',m[4])][:int(m[3])]])
S=S[1:]  # drop the once-per-boot ft1 0xd
le=lambda b:int.from_bytes(bytes(b),'little'); fmt=lambda pl:' '.join('%02x'%x for x in pl)
def reg(addr):  # Windows final value of a rxana register (0x12a10000 = rxanaA, +0x1000 = rxanaB)
    off=addr-0x12a10000
    if off<0 or off>=0x2000: return None
    blk='rxanaA' if off<0x1000 else 'rxanaB'
    return W.get((blk,off),0)
import difflib
# align the Surface table to our c1 by (ft, cmd) with difflib; unmatched positions keep c1
sm=difflib.SequenceMatcher(None,[tuple(x[:2]) for x in A],[tuple(x[:2]) for x in S],autojunk=False)
SA=[None]*len(A)
for tag,i1,i2,j1,j2 in sm.get_opcodes():
    if tag=='equal':
        for k in range(i2-i1): SA[i1+k]=S[j1+k]
print(f"c1 {len(A)} c2 {len(B)} surface {len(S)}; surface-aligned positions: {sum(x is not None for x in SA)}/{len(A)}")
# align c2 to c1 by position after its extra leading ft1 messages
off=len(B)-len(A)
B2=[None]*len(A)
j=0
for i,a in enumerate(A):
    while j<len(B) and B[j][:2]!=a[:2]: j+=1
    if j<len(B): B2[i]=B[j]; j+=1
# last write index per address
last={}
for i,a in enumerate(A):
    if a[1]==0xa0 and len(a[3])>=4 and a[3][2]==0xa1 and a[3][3]==0x12: last[le(a[3][0:4])]=i
rows=[]; notes=[]
for i,a in enumerate(A):
    ft,cmd,ln,p1=a; p2=B2[i][3] if B2[i] else None
    if SA[i] is None:
        rows.append((ft,cmd,ln,list(p1),'c1 (no Surface counterpart)')); continue
    s=SA[i][3]
    pick=list(s); why='surface'
    if cmd==0xa0:
        addr=le(s[0:4]); mask=le(s[4:8]); val=le(s[8:12])
        if last.get(addr)==i and reg(addr) is not None:
            want=reg(addr)&mask
            if (val&mask)!=want:
                pick=list(s[0:8])+list(want.to_bytes(4,'little')); why=f'value from Windows reg {addr:#x}={reg(addr):#010x} & mask'
            else: why='surface (consistent with Windows reg)'
    elif cmd in (0xa2,0x91):
        # 0xa2 carries the PHY data-rate/lane word (4-lane here, 2-lane on the Surface) and 0x91 is
        # firmware-specific; both of our captures agree on them, so they are ours, never the Surface's
        pick=list(p1); why='c1 (sensor/firmware specific; both captures agree)'
    else:
        if p2 is not None and p1==p2 and p1!=s: pick=list(p1); why='both captures agree'
        elif p1==s or (p2 is not None and p2==s): why='surface (= a capture)'
    rows.append((ft,cmd,ln,pick,why))
with open(out,'w') as f:
    f.write('/* SPDX-License-Identifier: GPL-2.0 */\n/*\n * CCU stream-on sequence for the Lenovo Yoga 9 2-in-1 16N1X11 (83N7) front camera (OV08X40,\n * CSI port 0, 4 lanes, 3840x2400). Message order from our Windows ccusnoop captures (identical\n * to the Surface Laptop Ultra\'s). The polled captures tear payloads, so the 0xa0 register\n * writes {addr, mask, value} are reconstructed from the Windows register dump: for the last\n * write to each rxana register, value = final register & mask. Everything else is the Surface\'s\n * payload unless both of our captures agree otherwise. Generated by tools/ccusnoop-reconstruct.py.\n */\nstruct ccucmd { u8 ft; u16 cmd; u16 len; u8 pl[48]; };\nstatic const struct ccucmd ccu_replay[] = {\n')
    for k,(ft,cmd,ln,pl,why) in enumerate(rows):
        f.write('\t{ %d, 0x%x, %d, { %s } },  /* %d: %s */\n'%(ft,cmd,ln,', '.join('0x%02x'%x for x in pl),k,why))
    f.write('};\n')
for k,(ft,cmd,ln,pl,why) in enumerate(rows):
    if why!='surface' : print(f"{k:2d} 0x{cmd:<3x} {fmt(pl):<50} {why}")
print("wrote",out)
