#!/usr/bin/env python3
"""Build golden_mmio.h / golden_omux_all.h (Surface driver format) from ccusnoop register dumps.
usage: ccusnoop-golden.py surface_kernel_dir out_dir capture1.log [capture2.log ...]
Offsets: the Surface's selection plus every register nonzero here that is stable across all
streaming snapshots (live counters/status excluded). Zero rows are kept where the Surface has them."""
import re,sys,subprocess
SU,OUT,LOGS=sys.argv[1],sys.argv[2],sys.argv[3:]
def dumps(log):
    D=[];cur=None
    for l in open(log,errors='replace'):
        l=l.rstrip('\r\n')
        if l.startswith('=== DUMP'): cur={}; D.append(cur); continue
        m=re.match(r'\s+(\w+)\+([0-9a-f]+):\s+(.*)',l)        # block names like camsv1dma, rxanaB, omux11
        if m and cur is not None:
            for i,v in enumerate(m[3].split()): cur[(m[1],int(m[2],16)+4*i)]=int(v,16)
    return D
alld=[dumps(l) for l in LOGS]
streaming=[d for D in alld for d in D if ('omux1',0x100a0) in d and d[('omux1',0x100a0)]]
last=streaming[-1]
live={k for d in streaming for k in d if any(x.get(k)!=d[k] for x in streaming)}
print(f"{len(streaming)} streaming snapshots; blocks: {sorted({b for b,o in last})}; live regs: {len(live)}")
def surf_offs(name):
    m=re.search(r'static const struct rw %s\[\] = \{(.*?)\};'%name,open(SU+'/golden_mmio.h').read(),re.S)
    return [int(a,16) for a in re.findall(r'\{\s*(0x[0-9a-f]+),',m[1])]
def table(name,blk,base,skip=()):
    offs=set(surf_offs(name)); mine={o-base:v for (b,o),v in last.items() if b==blk}
    assert mine, f"block {blk} missing from the dump"
    offs|={o for o,v in mine.items() if v}
    offs-={o for o in offs if (blk,o+base) in live}; offs-=set(skip)
    return [(o,mine.get(o,0)) for o in sorted(offs)]
out=['/* SPDX-License-Identifier: GPL-2.0 */','/*',' * Directly-mapped camera register state while Windows streams the front camera of the',' * Lenovo Yoga 9 2-in-1 16N1X11 (83N7): OV08X40, CSI port 0, 4 lanes, 3840x2400 RAW10,',' * read with tools/windows-ccusnoop (%d streaming snapshots, 2026-11-14). Offsets are the'%len(streaming),' * Surface driver\'s selection plus every register nonzero here that does not change between',' * snapshots (live counters and status are left out). Generated by tools/ccusnoop-golden.py.',' */','struct rw { u32 off; u32 val; };']
def emit(name,rows,note=''):
    out.append(f'static const struct rw {name}[] = {{{note}')
    out.extend([f'\t{{ 0x{o:04x}, 0x{v:08x} }},' for o,v in rows]); out.append('};'); print(f"{name}: {len(rows)} rows")
emit('g_dphy',table('g_dphy','dphy',0x2000),'\t/* seninf +0x2000 */')
emit('g_mactop',table('g_mactop','mactop',0x4000),'\t/* +0x4000 */')
emit('g_maccsi',table('g_maccsi','maccsi',0x5000),'\t/* +0x5000; +0x00 (CSI2_EN = 0xf, 4 lanes) is written last by the driver */')
emit('g_camsv1',table('g_camsv1','camsv1',0x10000,skip=(0x060,0x584)),'\t/* camsv_b central; 0x580/0x588/0x58c/0x594 are rewritten by the driver */')
emit('g_camsv1dma',table('g_camsv1dma','camsv1dma',0x10000),'\t/* camsv_b DMATOP (+0x1000); 0x1240-0x1250 per frame by the driver */')
open(OUT+'/golden_mmio.h','w').write('\n'.join(out)+'\n')
o2=['/* SPDX-License-Identifier: GPL-2.0 */','/* Windows streaming outmux state on the 83N7 (tools/windows-ccusnoop), all non-waived',' * outmuxes, zeros included for 0x04-0xfc. Used: 1 and 7 (src 0), unused parked at src 3.',' * +0x28 is a live debug port and is left out. Generated by tools/ccusnoop-golden.py. */','struct omw { u8 mux; u16 off; u32 val; };','static const struct omw g_omux_all[] = {']
for m in [0,1,4,6,7,9,11,13]:
    mine={o-m*0x10000:v for (b,o),v in last.items() if b==f'omux{m}'}
    for o in list(range(0x04,0x100,4))+([0x108,0x124,0x140,0x15c] if m in (0,1) else []):
        if o!=0x28: o2.append(f'\t{{ {m}, 0x{o:03x}, 0x{mine.get(o,0):08x} }},')
o2.append('};'); open(OUT+'/golden_omux_all.h','w').write('\n'.join(o2)+'\n'); print('omux rows',len(o2)-6)
